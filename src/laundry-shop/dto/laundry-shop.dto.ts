import { IsNotEmpty, IsString, IsOptional, IsEmail, IsBoolean, IsNumber, ValidateIf } from 'class-validator';
import { Transform } from 'class-transformer';
import { ApiProperty } from '@nestjs/swagger';

export class CreateLaundryShopDto {
  @ApiProperty({ example: 'Sunrise Laundry', description: 'Mandatory laundry shop name' })
  @Transform(({ value }) => (typeof value === 'string' ? value.trim() : value))
  @IsString()
  @IsNotEmpty()
  shopName!: string;

  @ApiProperty({ example: 'SHOP-1001', required: false, description: 'Optional shop code. If omitted, auto-generated by backend.' })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  shopCode?: string;

  @ApiProperty({ example: 'Rajesh Kumar', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  ownerName?: string;

  @ApiProperty({ example: '9876543210', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  contactNumber?: string;

  @ApiProperty({ example: 'sunrise@laundry.com', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @ValidateIf((o, v) => v !== undefined && v !== null && v !== '')
  @IsEmail()
  @IsOptional()
  email?: string;

  @ApiProperty({ example: '12 MG Road, Koramangala', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  address?: string;

  @ApiProperty({ example: 'Bangalore', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  city?: string;

  @ApiProperty({ example: 'Karnataka', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  state?: string;

  @ApiProperty({ example: '560034', required: false })
  @Transform(({ value }) => (!value || typeof value !== 'string' || value.trim() === '' ? undefined : value.trim()))
  @IsString()
  @IsOptional()
  pincode?: string;

  @ApiProperty({ example: 50, required: false, description: 'Max orders per day' })
  @Transform(({ value }) => (value === '' || value === null || value === undefined ? undefined : Number(value)))
  @IsNumber()
  @IsOptional()
  capacity?: number;

  @ApiProperty({ example: true, required: false })
  @IsBoolean()
  @IsOptional()
  isActive?: boolean;
}

